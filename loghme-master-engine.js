  CouponEngine.prototype.evaluate = function (code, cart) {
    const result = {
      ok: false,
      code: null,
      title: null,
      discountAmount: 0,
      freeDelivery: false,
      error: null,
      errorLabel: null
    };
    const normalized = String(code || '').trim().toUpperCase();
    if (!normalized) {
      result.error = 'empty';
      result.errorLabel = 'کد تخفیف را وارد کنید.';
      return result;
    }
    const def = COUPON_DEFINITIONS[normalized];
    if (!def) {
      result.error = 'invalid';
      result.errorLabel = 'کد تخفیف نامعتبر است.';
      return result;
    }
    if (!cart || cart.isEmpty()) {
      result.error = 'empty_cart';
      result.errorLabel = 'سبد خرید خالی است.';
      return result;
    }

    const items = cart.getItems();
    const subtotal = cart.getSubtotal();
    const vendor = cart.getVendor();

    if (def.minOrder && subtotal < def.minOrder) {
      result.error = 'min_order';
      result.errorLabel = 'حداقل مبلغ سفارش برای این کد ' + L.formatPrice(def.minOrder) + ' تومان است.';
      return result;
    }

    if (def.firstOrderOnly) {
      const completedOrders = this.ctx.getCompletedOrderCount ? this.ctx.getCompletedOrderCount() : 0;
      if (completedOrders > 0) {
        result.error = 'first_order';
        result.errorLabel = 'این کد فقط برای اولین سفارش قابل استفاده است.';
        return result;
      }
    }

    if (def.timeRestriction) {
      const h = new Date().getHours();
      const from = def.timeRestriction.from;
      const to = def.timeRestriction.to;
      const inWindow = from > to ? (h >= from || h < to) : (h >= from && h < to);
      if (!inWindow) {
        result.error = 'time';
        result.errorLabel = 'این کد فقط در ساعات شبانه قابل استفاده است.';
        return result;
      }
    }

    if (def.vendorRestricted && Array.isArray(def.vendorRestricted)) {
      if (!vendor || def.vendorRestricted.indexOf(vendor.id) === -1) {
        result.error = 'vendor';
        result.errorLabel = 'این کد برای فروشگاه انتخابی شما معتبر نیست.';
        return result;
      }
    }

    let discountAmount = 0;
    let freeDelivery = false;

    if (def.type === 'fixed') {
      discountAmount = Math.min(def.amount, subtotal);
    } else if (def.type === 'percent') {
      const raw = Math.round(subtotal * (def.percent / 100));
      discountAmount = def.maxDiscount ? Math.min(raw, def.maxDiscount) : raw;
    } else if (def.type === 'categoryPercent') {
      const categoryItems = items.filter(it => it.product && it.product.categoryId === def.categoryId);
      const categorySubtotal = categoryItems.reduce((s, it) => s + it.lineTotal, 0);
      if (categorySubtotal === 0) {
        result.error = 'category_empty';
        const labels = {
          fruits: 'میوه', vegetables: 'سبزیجات', dairy: 'لبنیات',
          meat: 'گوشت و پروتئین', bread: 'نان', canned: 'کنسرو',
          frozen: 'منجمد', snacks: 'تنقلات', drinks: 'نوشیدنی',
          household: 'خانه‌داری', personal: 'بهداشتی', baby: 'نوزاد',
          pet: 'حیوانات', spices: 'ادویه', dry: 'خشکبار'
        };
        result.errorLabel = 'سبد شما فاقد محصولات دسته «' + (labels[def.categoryId] || def.categoryId) + '» است.';
        return result;
      }
      const raw = Math.round(categorySubtotal * (def.percent / 100));
      discountAmount = def.maxDiscount ? Math.min(raw, def.maxDiscount) : raw;
    } else if (def.type === 'freeDelivery') {
      freeDelivery = true;
    }

    if (discountAmount < 0) discountAmount = 0;
    if (discountAmount > subtotal) discountAmount = subtotal;

    result.ok = true;
    result.code = def.code;
    result.title = def.title;
    result.discountAmount = discountAmount;
    result.freeDelivery = freeDelivery;
    return result;
  };

