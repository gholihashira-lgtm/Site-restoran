  Cart.prototype.hydrate = function (data) {
    if (!data || typeof data !== 'object') return false;
    try {
      const s = emptyCart();
      if (data.items && typeof data.items === 'object') {
        for (const k in data.items) {
          const item = data.items[k];
          const pid = Number(item.productId || k);
          if (!L.productById(pid)) continue;
          s.items[String(pid)] = {
            productId: pid,
            quantity: L.clamp(item.quantity || 1, 1, 99),
            addons: Array.isArray(item.addons) ? item.addons : [],
            addedAt: item.addedAt || Date.now()
          };
        }
      }
      s.vendorId = s.items && Object.keys(s.items).length > 0 ? (data.vendorId || null) : null;
      s.couponCode = data.couponCode || null;
      s.deliveryMode = data.deliveryMode === 'pickup' ? 'pickup' : 'delivery';
      s.userLat = Number(data.userLat) || 35.7860;
      s.userLng = Number(data.userLng) || 51.3740;
      s.notes = typeof data.notes === 'string' ? data.notes : '';
      s.pickupSlot = data.pickupSlot || null;
      this.state = s;
      return true;
    } catch (e) {
      return false;
    }
  };

