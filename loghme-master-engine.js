  function toPersianDigits(n) {
    if (n === null || n === undefined) return '';
    return String(n).replace(/\d/g, d => FA_DIGITS[+d]);
  }

  function toEnglishDigits(s) {
    if (s === null || s === undefined) return '';
    return String(s).replace(/[۰-۹]/g, d => EN_DIGITS[FA_DIGITS.indexOf(d)]);
  }

  function faNormalize(input) {
    if (input === null || input === undefined) return '';
    let s = String(input);
    s = s.replace(/[\u064B-\u065F\u0670\u06D6-\u06ED]/g, '');
    s = s.replace(/\u200c/g, ' ').replace(/\u200d/g, '').replace(/\uFEFF/g, '');
    s = s.replace(/[يكةۀ]/g, c => AR_FA_MAP[c] || c);
    s = s.replace(/[أإآا]/g, 'ا').replace(/[ؤئ]/g, 'ی');
    s = s.replace(/[.,!?؟،؛:;"'`()\[\]{}<>«»\u2018\u2019\u201C\u201D\u2013\u2014_\-\\\/|]/g, ' ');
    s = s.replace(/\s+/g, ' ').trim().toLowerCase();
    return s;
  }

  function formatPrice(n) {
    const num = Math.max(0, Math.round(Number(n) || 0));
    let out = '';
    const s = String(num);
    for (let i = s.length - 1, c = 0; i >= 0; i--, c++) {
      if (c === 3) { out = ',' + out; c = 0; }
      out = s[i] + out;
    }
    return toPersianDigits(out);
  }

  function formatDecimal(n, digits) {
    const d = digits == null ? 1 : digits;
    return toPersianDigits(Number(n || 0).toFixed(d));
  }

  function clamp(v, min, max) {
    const n = Number(v);
    if (Number.isNaN(n)) return min;
    return Math.min(max, Math.max(min, n));
  }

  function fnvHash(str) {
    let h = 0x811c9dc5 >>> 0;
    const s = String(str);
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  }

  function mulberry32(seed) {
    let a = seed >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) | 0;
      let t = Math.imul(a ^ (a >>> 15), 1 | a);
      t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function rngFor(seedStr) { return mulberry32(fnvHash(seedStr)); }

  function pick(rng, arr) { return arr[Math.floor(rng() * arr.length) % arr.length]; }

  function pickInt(rng, min, max) { return Math.floor(min + rng() * (max - min + 1)); }

  function roundTo(n, step) {
    const s = step || 1;
    return Math.round(n / s) * s;
  }

  function deepClone(o) {
    try { return JSON.parse(JSON.stringify(o)); } catch (e) { return o; }
  }

  function debounce(fn, wait) {
    let t = null;
    return function () {
      const args = arguments, ctx = this;
      if (t) clearTimeout(t);
      t = setTimeout(() => { t = null; fn.apply(ctx, args); }, wait);
    };
  }

  function throttle(fn, wait) {
    let last = 0, timer = null;
    return function () {
      const args = arguments, ctx = this, now = Date.now();
      if (now - last >= wait) { last = now; fn.apply(ctx, args); }
      else if (!timer) {
        timer = setTimeout(() => { timer = null; last = Date.now(); fn.apply(ctx, args); }, wait - (now - last));
      }
    };
  }

  function escapeHtml(s) {
    if (s === null || s === undefined) return '';
    return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }[c]));
  }

  function uid(prefix) {
    const p = prefix || 'id';
    return p + '-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 8);
  }

  function degToRad(deg) { return deg * Math.PI / 180; }

  function haversineKm(lat1, lng1, lat2, lng2) {
    const R = 6371;
    const dLat = degToRad(lat2 - lat1);
    const dLng = degToRad(lng2 - lng1);
    const a = Math.sin(dLat / 2) ** 2 + Math.cos(degToRad(lat1)) * Math.cos(degToRad(lat2)) * Math.sin(dLng / 2) ** 2;
    return 2 * R * Math.asin(Math.sqrt(a));
  }

  function catmullRom(p0, p1, p2, p3, t) {
    const t2 = t * t, t3 = t2 * t;
    return 0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t2 + (-p0 + 3 * p1 - 3 * p2 + p3) * t3);
  }

  function cubicBezier(p0, p1, p2, p3, t) {
    const u = 1 - t;
    const uu = u * u, tt = t * t;
    return uu * u * p0 + 3 * uu * t * p1 + 3 * u * tt * p2 + tt * t * p3;
  }

