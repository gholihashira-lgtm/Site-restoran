  function EventBus() {
    this._handlers = new Map();
    this._wildcard = new Set();
  }

  EventBus.prototype.on = function (event, handler) {
    if (typeof handler !== 'function') return function () {};
    if (event === '*') {
      this._wildcard.add(handler);
      const self = this;
      return function () { self._wildcard.delete(handler); };
    }
    if (!this._handlers.has(event)) this._handlers.set(event, new Set());
    this._handlers.get(event).add(handler);
    const self = this;
    return function () {
      const s = self._handlers.get(event);
      if (s) s.delete(handler);
    };
  };

  EventBus.prototype.once = function (event, handler) {
    const self = this;
    const off = this.on(event, function (payload, name) {
      off();
      handler(payload, name);
    });
    return off;
  };

  EventBus.prototype.off = function (event, handler) {
    if (event === '*') { this._wildcard.delete(handler); return; }
    const set = this._handlers.get(event);
    if (set) set.delete(handler);
  };

  EventBus.prototype.emit = function (event, payload) {
    const set = this._handlers.get(event);
    if (set) {
      set.forEach(function (cb) {
        try { cb(payload, event); } catch (e) { console.warn('[EventBus]', event, e); }
      });
    }
    this._wildcard.forEach(function (cb) {
      try { cb(payload, event); } catch (e) { console.warn('[EventBus:*]', e); }
    });
    if (typeof global.dispatchEvent === 'function') {
      try {
        global.dispatchEvent(new CustomEvent('supermarket:' + event, { detail: payload }));
      } catch (e) {}
    }
  };

