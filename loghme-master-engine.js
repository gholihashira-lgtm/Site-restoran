  function scoreProduct(entry, queryTokens, opts) {
    if (queryTokens.length === 0) return 0;
    const opts2 = opts || {};
    let score = 0;

    const titleScore = scoreTokenMatch(queryTokens, entry.normTitle);
    if (entry.normTitle === queryTokens.join(' ')) {
      score += 100;
    } else if (titleScore > 0.85) {
      score += 100;
    } else if (titleScore > 0.4) {
      score += 60 * titleScore;
    } else {
      score += 24 * titleScore;
    }

    const catScore = scoreTokenMatch(queryTokens, entry.normCategory);
    if (catScore > 0.5) score += 40 * catScore;

    const descScore = scoreTokenMatch(queryTokens, entry.normDesc);
    score += 20 * descScore;

    const subScore = scoreTokenMatch(queryTokens, entry.normSubtype);
    if (subScore > 0.6) score += 30;

    score += entry.rating * 3;
    score += Math.min(entry.reviews / 200, 6);
    score += entry.discount * 0.35;

    if (opts2.vendorId && entry.ref.vendorId === opts2.vendorId) score += 35;
    if (opts2.categoryId && entry.ref.categoryId === opts2.categoryId) score += 25;
    if (opts2.maxPrice && entry.price > opts2.maxPrice) score -= 60;
    if (opts2.minRating && entry.rating < opts2.minRating) score -= 80;

    return score;
  }

  function scoreVendor(entry, queryTokens) {
    if (queryTokens.length === 0) return 0;
    let score = 0;
    const nameScore = scoreTokenMatch(queryTokens, entry.normName);
    if (entry.normName === queryTokens.join(' ')) score += 100;
    else if (nameScore > 0.8) score += 90;
    else score += 55 * nameScore;
    const typeScore = scoreTokenMatch(queryTokens, entry.normType);
    score += 30 * typeScore;
    score += entry.rating * 4;
    score += Math.min(entry.reviews / 500, 5);
    return score;
  }

  function performSearch(query, opts) {
    const options = opts || {};
    const q = String(query || '').trim();
    if (!q) return { products: [], vendors: [], categories: [], total: 0 };

    const tokens = tokenize(q);
    if (tokens.length === 0) return { products: [], vendors: [], categories: [], total: 0 };

    const idx = L._searchIndex;
    if (!idx) return { products: [], vendors: [], categories: [], total: 0 };

    const prefixMatches = new Set();
    idx.productTrie.startsWith(q).forEach(id => prefixMatches.add(id));

    const scoredProducts = [];
    const limit = options.limit || 40;
    for (const entry of idx.products) {
      let sc = scoreProduct(entry, tokens, options);
      if (prefixMatches.has(entry.id)) sc += 18;
      if (sc > 0.5) scoredProducts.push({ entry, score: sc });
    }
    scoredProducts.sort((a, b) => b.score - a.score);

    const scoredVendors = [];
    for (const entry of idx.vendors) {
      const sc = scoreVendor(entry, tokens);
      if (sc > 0.5) scoredVendors.push({ entry, score: sc });
    }
    scoredVendors.sort((a, b) => b.score - a.score);

    const categoryMap = new Map();
    for (const entry of scoredProducts.slice(0, limit)) {
      const cat = entry.entry.ref.categoryId;
      categoryMap.set(cat, (categoryMap.get(cat) || 0) + 1);
    }
    const categories = Array.from(categoryMap.entries())
      .sort((a, b) => b[1] - a[1])
      .slice(0, 8)
      .map(([id, count]) => ({ id, count }));

    return {
      products: scoredProducts.slice(0, limit).map(s => ({ ref: s.entry.ref, score: s.score })),
      vendors: scoredVendors.slice(0, options.vendorLimit || 12).map(s => ({ ref: s.entry.ref, score: s.score })),
      categories: categories,
      total: scoredProducts.length + scoredVendors.length
    };
  }

  function suggest(query, limit) {
    const q = String(query || '').trim();
    if (!q) return [];
    const idx = L._searchIndex;
    if (!idx) return [];
    const ids = idx.productTrie.startsWith(q).slice(0, (limit || 6) * 3);
    const seen = new Set();
    const out = [];
    for (const id of ids) {
      const entry = idx.productById.get(id);
      if (!entry) continue;
      const title = entry.ref.title;
      if (seen.has(title)) continue;
      seen.add(title);
      out.push(title);
      if (out.length >= (limit || 6)) break;
    }
    return out;
  }

