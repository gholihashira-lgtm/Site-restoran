  Cart.prototype.getItems = function () {
    return Object.keys(this.state.items).map(k => {
      const item = this.state.items[k];
      const product = L.productById(item.productId);
      const addonSum = (item.addons || []).reduce((s, a) => s + (a.price || 0), 0);
      const unitPrice = product ? product.price + addonSum : 0;
      const lineTotal = unitPrice * item.quantity;
      return {
        productId: item.productId,
        product: product,
        quantity: item.quantity,
        addons: item.addons || [],
        unitPrice: unitPrice,
        lineTotal: lineTotal,
        lineSavings: product && product.discount > 0 ? (product.originalPrice - product.price) * item.quantity : 0
      };
    });
  };

  Cart.prototype.getSubtotal = function () {
    return this.getItems().reduce((s, it) => s + it.lineTotal, 0);
  };

  Cart.prototype.getOriginalSubtotal = function () {
    return this.getItems().reduce((s, it) => {
      if (!it.product) return s;
      const addonSum = (it.addons || []).reduce((a, b) => a + (b.price || 0), 0);
      return s + (it.product.originalPrice + addonSum) * it.quantity;
    }, 0);
  };

