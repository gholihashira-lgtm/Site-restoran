  function DeliveryCalculator(opts) {
    const o = opts || {};
    this.baseFee = o.baseFee != null ? o.baseFee : 12000;
    this.perKmFee = o.perKmFee != null ? o.perKmFee : 4000;
    this.freeThreshold = o.freeThreshold != null ? o.freeThreshold : 600000;
    this.maxRadiusKm = o.maxRadiusKm != null ? o.maxRadiusKm : 12;
    this.weightTiers = [
      { kg: 3, multiplier: 1.0 },
      { kg: 8, multiplier: 1.15 },
      { kg: 15, multiplier: 1.35 },
      { kg: 25, multiplier: 1.6 },
      { kg: Infinity, multiplier: 2.0 }
    ];
  }

  DeliveryCalculator.prototype.getWeightMultiplier = function (kg) {
    for (const t of this.weightTiers) {
      if (kg <= t.kg) return t.multiplier;
    }
    return 2.0;
  };

  DeliveryCalculator.prototype.compute = function (vendor, userLat, userLng, items, extras, weightKg) {
    const ex = extras || {};
    const result = {
      ok: true,
      fee: 0,
      distanceKm: 0,
      surgeFactor: 1.0,
      weightMultiplier: 1.0,
      weightKg: weightKg || 0,
      subtotal: 0,
      freeByThreshold: false,
      freeByCoupon: !!ex.couponFreeDelivery,
      pickup: ex.deliveryMode === 'pickup',
      breakdown: {}
    };

    if (!vendor) {
      result.ok = false;
      result.error = 'no_vendor';
      return result;
    }

    if (result.pickup) {
      result.fee = 0;
      result.breakdown = { note: 'pickup' };
      return result;
    }

    const dist = L.haversineKm(vendor.location.lat, vendor.location.lng, Number(userLat) || vendor.location.lat, Number(userLng) || vendor.location.lng);
    result.distanceKm = Math.round(dist * 100) / 100;

    if (dist > this.maxRadiusKm) {
      result.ok = false;
      result.error = 'out_of_range';
      result.errorLabel = 'آدرس شما خارج از محدوده ارسال این فروشگاه است.';
      return result;
    }

    const wMul = this.getWeightMultiplier(result.weightKg);
    result.weightMultiplier = wMul;
    const surge = L.surgeMultiplier();
    result.surgeFactor = surge;

    const distanceFee = Math.max(0, dist - 1) * this.perKmFee;
    const rawFee = (vendor.deliveryFee || this.baseFee) + distanceFee;
    let fee = Math.round(rawFee * wMul * surge);

    const subtotal = (items || []).reduce((s, it) => s + it.lineTotal, 0);
    result.subtotal = subtotal;

    if (subtotal >= this.freeThreshold) {
      result.freeByThreshold = true;
    }

    if (result.freeByThreshold || result.freeByCoupon) {
      fee = 0;
    }

    result.fee = Math.max(0, fee);
    result.breakdown = {
      baseVendorFee: vendor.deliveryFee || 0,
      distanceKm: result.distanceKm,
      distanceFee: distanceFee,
      weightMultiplier: wMul,
      weightKg: result.weightKg,
      surgeFactor: surge,
      freeByThreshold: result.freeByThreshold,
      freeByCoupon: result.freeByCoupon
    };

    return result;
  };

