  function Trie() {
    this.root = { children: new Map(), ids: [], isWord: false };
    this.size = 0;
  }

  Trie.prototype.insert = function (word, id) {
    if (!word) return;
    const w = L.faNormalize(word);
    if (!w) return;
    let node = this.root;
    for (let i = 0; i < w.length; i++) {
      const c = w[i];
      if (!node.children.has(c)) {
        node.children.set(c, { children: new Map(), ids: [], isWord: false });
      }
      node = node.children.get(c);
      if (node.ids.indexOf(id) === -1) node.ids.push(id);
    }
    node.isWord = true;
    this.size++;
  };

