  function levenshtein(a, b) {
    const s = String(a == null ? '' : a);
    const t = String(b == null ? '' : b);
    const n = s.length, m = t.length;
    if (n === 0) return m;
    if (m === 0) return n;
    if (Math.abs(n - m) > 24) return 24;
    let prev = new Array(m + 1);
    let curr = new Array(m + 1);
    for (let j = 0; j <= m; j++) prev[j] = j;
    for (let i = 1; i <= n; i++) {
      curr[0] = i;
      const ca = s.charCodeAt(i - 1);
      for (let j = 1; j <= m; j++) {
        const cost = ca === t.charCodeAt(j - 1) ? 0 : 1;
        const del = prev[j] + 1;
        const ins = curr[j - 1] + 1;
        const sub = prev[j - 1] + cost;
        curr[j] = Math.min(del, ins, sub);
      }
      const tmp = prev; prev = curr; curr = tmp;
    }
    return prev[m];
  }

  function levenshteinRatio(a, b) {
    const maxLen = Math.max(a.length, b.length);
    if (maxLen === 0) return 1;
    return 1 - (levenshtein(a, b) / maxLen);
  }

  function nGrams(str, n) {
    const s = '  ' + String(str || '') + '  ';
    const size = n || 3;
    const out = [];
    for (let i = 0; i < s.length - size + 1; i++) {
      out.push(s.substr(i, size));
    }
    return out;
  }

  function nGramSimilarity(a, b, n) {
    const ga = nGrams(a, n || 2);
    const gb = nGrams(b, n || 2);
    if (ga.length === 0 || gb.length === 0) return 0;
    const map = new Map();
    ga.forEach(g => map.set(g, (map.get(g) || 0) + 1));
    let overlap = 0;
    gb.forEach(g => {
      const c = map.get(g) || 0;
      if (c > 0) { overlap++; map.set(g, c - 1); }
    });
    return (2 * overlap) / (ga.length + gb.length);
  }

  function tokenize(str) {
    const norm = L.faNormalize(str);
    if (!norm) return [];
    return norm.split(' ').filter(t => t.length > 0);
  }

  function scoreTokenMatch(queryTokens, targetNorm) {
    if (!targetNorm) return 0;
    if (queryTokens.length === 0) return 0;
    let total = 0;
    for (const q of queryTokens) {
      if (targetNorm === q) { total += 1; continue; }
      const idx = targetNorm.indexOf(q);
      if (idx === 0) { total += 0.92; continue; }
      if (idx > 0) { total += 0.72; continue; }
      const ng = nGramSimilarity(q, targetNorm, 2);
      if (ng >= 0.7) { total += 0.55 * ng; continue; }
      const tokens = targetNorm.split(' ');
      let best = 0;
      for (const t of tokens) {
        const lr = levenshteinRatio(q, t);
        if (lr > best) best = lr;
        const ngT = nGramSimilarity(q, t, 2);
        if (ngT > best) best = ngT;
      }
      total += best * 0.6;
    }
    return total / queryTokens.length;
  }

