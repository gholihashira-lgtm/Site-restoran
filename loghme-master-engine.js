  function buildWaypoints(vendor, destination, extraPoints) {
    const v = { lat: vendor.location.lat, lng: vendor.location.lng };
    const d = { lat: Number(destination.lat), lng: Number(destination.lng) };
    const pts = [v];
    const mid = extraPoints && extraPoints.length > 0 ? extraPoints : null;
    if (mid) {
      mid.forEach(p => pts.push({ lat: Number(p.lat), lng: Number(p.lng) }));
    } else {
      const seed = L.fnvHash(v.lat + ':' + v.lng + ':' + d.lat + ':' + d.lng);
      const rng = L.mulberry32(seed);
      const count = 4 + Math.floor(rng() * 3);
      const dLat = d.lat - v.lat;
      const dLng = d.lng - v.lng;
      const perpLat = -dLng * 0.15;
      const perpLng = dLat * 0.15;
      for (let i = 1; i <= count; i++) {
        const t = i / (count + 1);
        const curve = Math.sin(t * Math.PI);
        const wobble = (rng() - 0.5) * 0.6;
        pts.push({
          lat: v.lat + dLat * t + perpLat * curve * (0.5 + wobble * 0.4),
          lng: v.lng + dLng * t + perpLng * curve * (0.5 + wobble * 0.4)
        });
      }
    }
    pts.push(d);
    return pts;
  }

  function catmullRomPath(points, samplesPerSegment) {
    if (!points || points.length < 2) return [];
    const sps = samplesPerSegment || 24;
    const out = [];
    const pts = points.slice();
    const first = { lat: pts[0].lat + (pts[0].lat - pts[1].lat), lng: pts[0].lng + (pts[0].lng - pts[1].lng) };
    const last = { lat: pts[pts.length - 1].lat + (pts[pts.length - 1].lat - pts[pts.length - 2].lat), lng: pts[pts.length - 1].lng + (pts[pts.length - 1].lng - pts[pts.length - 2].lng) };
    const ext = [first].concat(pts).concat([last]);
    for (let i = 1; i < ext.length - 2; i++) {
      const p0 = ext[i - 1], p1 = ext[i], p2 = ext[i + 1], p3 = ext[i + 2];
      for (let s = 0; s < sps; s++) {
        const t = s / sps;
        out.push({
          lat: L.catmullRom(p0.lat, p1.lat, p2.lat, p3.lat, t),
          lng: L.catmullRom(p0.lng, p1.lng, p2.lng, p3.lng, t)
        });
      }
    }
    out.push({ lat: ext[ext.length - 2].lat, lng: ext[ext.length - 2].lng });
    return out;
  }

